create table if not exists public.fnb_staff_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check(role in ('operator','demo_reviewer')),
  created_at timestamptz not null default now()
);
create table if not exists public.fnb_reports (
  id text primary key,
  client_id text not null unique,
  category text not null check(category in ('Leak or burst pipe','No water','Low pressure','Water quality','Other')),
  zone text not null check(zone in ('Khayelitsha East','Mitchells Plain','Bellville South','Cape Flats West')),
  details text not null check(char_length(details) between 8 and 500),
  status text not null default 'Received' check(status in ('Received','Investigating','Resolved')),
  routing_stage text not null default 'Not routed',
  review jsonb,
  field_evidence jsonb,
  operator_note text,
  source text not null default 'Resident demonstration',
  routed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fnb_client_id_pattern check(client_id ~ '^local-[0-9a-fA-F-]{36}$')
);
create table if not exists public.fnb_incidents (
  id text primary key,
  payload jsonb not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.fnb_audit_events (
  id uuid primary key default gen_random_uuid(),
  report_id text,
  action text not null,
  detail text not null,
  actor_id uuid,
  created_at timestamptz not null default now()
);
create table if not exists public.fnb_rate_events (
  id bigint generated by default as identity primary key,
  client_key_hash text not null,
  action text not null,
  created_at timestamptz not null default now()
);
create index if not exists fnb_reports_zone_idx on public.fnb_reports (zone,created_at desc);
create index if not exists fnb_reports_status_idx on public.fnb_reports(status,created_at desc);
create index if not exists fnb_audit_created_idx on public.fnb_audit_events(created_at desc);
create index if not exists fnb_rate_idx on public.fnb_rate_events(client_key_hash,action,created_at desc);
